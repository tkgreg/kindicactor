// Generates Sources/KIndicatorCore/KeyboardLayouts+V6Ultra8K.swift from the keyboard
// definitions Keychron Launcher loads, so the app needs no network for them.
//
//   swift Tools/make-layouts.swift Sources/KIndicatorCore/KeyboardLayouts+V6Ultra8K.swift

import Foundation

let vendorID = 0x3434
/// USB product ID and the Swift name of each layout.
let layouts: [(productID: Int, name: String)] = [
    (0x0C60, "v6Ultra8KANSI"),
    (0x0C61, "v6Ultra8KISO"),
    (0x0C62, "v6Ultra8KJIS"),
]

func definitionURL(productID: Int) -> URL {
    URL(string: "https://launcher.keychron.com/static/device/\(vendorID * 65536 + productID)/json/v3.json")!
}

func number(_ value: Any?) -> Double {
    (value as? NSNumber)?.doubleValue ?? 0
}

func literal(_ value: Double) -> String {
    String(format: "%g", value)
}

func swiftString(_ text: String) -> String {
    "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
}

guard CommandLine.arguments.count == 2 else {
    print("Usage: swift Tools/make-layouts.swift <output.swift>")
    exit(1)
}

var output = """
    // Generated by Tools/make-layouts.swift; don't edit. From the keyboard definitions Keychron
    // Launcher loads: https://launcher.keychron.com/static/device/<vendor ID · 65536 + product ID>/json/v3.json

    extension KeyboardLayout {
        /// Bundled layouts by USB product ID.
        static let bundled: [Int: KeyboardLayout] = [
    \(layouts.map { String(format: "        0x%04X: %@,", $0.productID, $0.name) }.joined(separator: "\n"))
        ]

    """

for layout in layouts {
    let data = try Data(contentsOf: definitionURL(productID: layout.productID))
    guard let definition = try JSONSerialization.jsonObject(with: data) as? [String: Any],
          let name = definition["name"] as? String,
          let matrix = definition["matrix"] as? [String: Any],
          let geometry = definition["layouts"] as? [String: Any],
          let keys = geometry["keys"] as? [[String: Any]]
    else {
        print("Unexpected definition for \(String(format: "%04X", layout.productID))")
        exit(1)
    }
    let customNames = (definition["customKeycodes"] as? [[String: Any]] ?? []).map {
        ($0["shortName"] as? String) ?? ($0["name"] as? String) ?? ""
    }

    let keyLines = keys.map { key -> String in
        if number(key["r"]) != 0 { print("warning: \(name) has a rotated key, drawn unrotated") }
        let x = number(key["x"]), y = number(key["y"])
        let width = key["w"] == nil ? 1 : number(key["w"])
        let height = key["h"] == nil ? 1 : number(key["h"])
        let kind = switch key["color"] as? String {
        case "mod": ".modifier"
        case "accent": ".accent"
        default: ".alpha"
        }
        var line = "            layoutKey(\(Int(number(key["row"]))), \(Int(number(key["col"]))), \(literal(x)), \(literal(y)), "
            + "\(literal(width)), \(literal(height)), \(kind)"
        if key["ei"] != nil { line += ", knob: true" }
        if key["w2"] != nil || key["h2"] != nil || key["x2"] != nil || key["y2"] != nil {
            // KLE: the second rectangle is offset from the first one's corner.
            let second = [x + number(key["x2"]), y + number(key["y2"]),
                          key["w2"] == nil ? width : number(key["w2"]), key["h2"] == nil ? height : number(key["h2"])]
            line += ", second: KeyRect(x: \(literal(second[0])), y: \(literal(second[1])), "
                + "width: \(literal(second[2])), height: \(literal(second[3])))"
        }
        return line + "),"
    }

    output += """

        /// \(name), \(keys.count) keys.
        static let \(layout.name) = KeyboardLayout(
            name: \(swiftString(name)), width: \(literal(number(geometry["width"]))), height: \(literal(number(geometry["height"]))),
            rows: \(Int(number(matrix["rows"]))), cols: \(Int(number(matrix["cols"]))),
            keys: [
    \(keyLines.joined(separator: "\n"))
            ],
            customKeycodeNames: [\(customNames.map(swiftString).joined(separator: ", "))]
        )

    """
}

output += """
    }

    private func layoutKey(_ row: Int, _ col: Int, _ x: Double, _ y: Double, _ width: Double, _ height: Double,
                           _ kind: LayoutKey.Kind, knob: Bool = false, second: KeyRect? = nil) -> LayoutKey {
        LayoutKey(position: KeyPosition(row: row, col: col), rect: KeyRect(x: x, y: y, width: width, height: height),
                  secondRect: second, kind: kind, isKnob: knob)
    }

    """

try output.write(toFile: CommandLine.arguments[1], atomically: true, encoding: .utf8)
print("Wrote \(CommandLine.arguments[1])")
